CREATE TABLE IF NOT EXISTS frame_window (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    window_id VARCHAR(32) NOT NULL UNIQUE,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sensor_id VARCHAR(64) NOT NULL,
    bssid VARCHAR(17) NOT NULL,
    channel SMALLINT NOT NULL,
    duration_ms INTEGER NOT NULL,
    beacon INTEGER NOT NULL,
    deauth INTEGER NOT NULL,
    disassoc INTEGER NOT NULL,
    retry INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS frame_window_stream_idx
    ON frame_window (sensor_id, bssid, channel, id DESC);

CREATE TABLE IF NOT EXISTS frame_calibration (
    sensor_id VARCHAR(64) NOT NULL,
    bssid VARCHAR(17) NOT NULL,
    channel SMALLINT NOT NULL,
    window_ids BIGINT[] NOT NULL,
    PRIMARY KEY (sensor_id, bssid, channel)
);
